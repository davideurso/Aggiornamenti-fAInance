function locale(lang: string): keyof typeof income {
  const code = String(lang || "it").toLowerCase().split(/[-_]/)[0];
  return Object.prototype.hasOwnProperty.call(income, code) ? code as keyof typeof income : "it";
}

export function incomeTypeTitle(lang: string) {
  return income[locale(lang)].title;
}

export function incomeTypeName(item: {id?: string; name?: string} | undefined, lang: string) {
  const id = item?.id as Exclude<keyof typeof income.it, "title">;
  if (id && Object.prototype.hasOwnProperty.call(income.it, id) && item?.name === income.it[id]) {
    return income[locale(lang)][id];
  }
  return item?.name || "";
}

const shoppingKeys = new Map(Object.entries(shopping.it).map(([key, text]) => [text, key as keyof typeof shopping.it]));

export function shoppingSettingsText(text: string, lang: string, page: string) {
  if (typeof text !== "string" || (page !== "sections" && !page?.startsWith("shopping_settings"))) return undefined;
  const labels = shopping[locale(lang)];
  if (page === "sections" && text !== shopping.it.title && text !== shopping.it.summary) return undefined;
  const prefix = shopping.it.title + " / ";
  if (text.startsWith(prefix)) {
    const key = shoppingKeys.get(text.slice(prefix.length));
    if (key) return labels.title + " / " + labels[key];
  }
  const key = shoppingKeys.get(text);
  return key ? labels[key] : undefined;
}
