import assert from 'node:assert/strict';
import {createFinanceEvolution,migrateFinanceEvolution} from '../src/data/financeEvolution.js';
import {createSavingsBucket,updateSavingsBucket} from '../src/finance/savingsBuckets.js';
import {setSavingsPlanAmount,savingsPlanSummary} from '../src/finance/savingsPlan.js';
import {budgetForPeriod,saveBudgetForPeriod,validateBudgetPlan} from '../src/finance/budgetEngine.js';
const legacy={income:2000,items:[{catId:1,amount:1500}]};
let data=createSavingsBucket(createFinanceEvolution(),{id:'travel',name:'Viaggio',currency:'EUR'});
data=createSavingsBucket(data,{id:'reserve',name:'Riserva',currency:'EUR'});
data.savings.buckets[0].balanceMinor=12345;
data.savings.buckets[0].goalId='existing-goal';
data.savings.entries=[{id:'entry',bucketId:'travel',amountMinor:12345,source:'extra'}];
const original=structuredClone(data);
data=setSavingsPlanAmount(data,legacy,'2026-08','travel',200,'EUR','future');
assert.deepEqual(data.savings,original.savings,'Planning never changes balances, entries or goals');
assert.deepEqual(budgetForPeriod(data,legacy,'2026-07'),legacy);
assert.equal(budgetForPeriod(data,legacy,'2026-09').savingsPlannedAmounts.travel,200);
data=setSavingsPlanAmount(data,legacy,'2026-09','travel',300,'EUR','month');
assert.equal(budgetForPeriod(data,legacy,'2026-08').savingsPlannedAmounts.travel,200);
assert.equal(budgetForPeriod(data,legacy,'2026-09').savingsPlannedAmounts.travel,300);
assert.equal(budgetForPeriod(data,legacy,'2026-10').savingsPlannedAmounts.travel,200);
for(const amount of [-1,0.5,NaN,Infinity,Number.MAX_SAFE_INTEGER+1]) assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','travel',amount,'EUR'),/INVALID/);
assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','travel',501,'EUR'),/EXCEEDED/);
assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','reserve',201,'EUR'),/EXCEEDED/);
assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','travel',1,'USD'),/CURRENCY/);
assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','missing',1,'EUR'),/NOT_FOUND/);
const inactive=updateSavingsBucket(data,'travel',{active:false});
assert.equal(savingsPlanSummary(budgetForPeriod(inactive,legacy,'2026-09')).allocated,300);
assert.throws(()=>setSavingsPlanAmount(inactive,legacy,'2026-09','travel',1,'EUR'),/INACTIVE/);
const plan=budgetForPeriod(data,legacy,'2026-09');
data=saveBudgetForPeriod(data,legacy,'2026-09',{...plan,items:[{catId:1,amount:1900}]},'month');
assert.equal(savingsPlanSummary(budgetForPeriod(data,legacy,'2026-09')).remaining,-200);
data=setSavingsPlanAmount(data,legacy,'2026-09','travel',200,'EUR');
assert.equal(savingsPlanSummary(budgetForPeriod(data,legacy,'2026-09')).remaining,-100,'Existing excess can be reduced gradually');
assert.throws(()=>setSavingsPlanAmount(data,legacy,'2026-09','travel',250,'EUR'),/EXCEEDED/);
data=setSavingsPlanAmount(data,legacy,'2026-09','travel',0,'EUR');
assert.equal(savingsPlanSummary(budgetForPeriod(data,legacy,'2026-09')).remaining,100);
assert.deepEqual(migrateFinanceEvolution(JSON.parse(JSON.stringify(data))),data);
assert.throws(()=>validateBudgetPlan({...legacy,savingsPlannedAmounts:{travel:1}}),/INVALID_SAVINGS_PLAN/);
assert.throws(()=>validateBudgetPlan({...legacy,savingsPlanCurrency:'EUR',savingsPlannedAmounts:{travel:-1}}),/INVALID_SAVINGS_PLAN_AMOUNT/);
assert.deepEqual(original.savings,data.savings);
console.log('Savings planning: month/future history, budget limits, stepwise correction, currencies, inactive categories, zero, validation and roundtrip passed');
