import assert from 'node:assert/strict';
import {createFinanceEvolution,migrateFinanceEvolution,mergeFinanceEvolution} from '../src/data/financeEvolution.js';
import {createSavingsBucket,updateSavingsBucket} from '../src/finance/savingsBuckets.js';
import {saveSavingsEntry,cancelSavingsEntry,savingsAmountMinor} from '../src/finance/savingsLedger.js';
import {setSavingsPlanAmount} from '../src/finance/savingsPlan.js';
import {loadTypeScript} from './loadTypeScript.mjs';
const stamp='2026-09-14T08:00:00.000Z';
let model=createSavingsBucket(createFinanceEvolution(),{id:'travel',name:'Vacanze',currency:'EUR'});
const legacy={income:1000,items:[{catId:1,amount:500}]};
model=setSavingsPlanAmount(model,legacy,'2026-09','travel',200,'EUR','future');
const before=structuredClone(model);
const input={id:'first',bucketId:'travel',currency:'EUR',date:'2026-09-14',amountMinor:15000,source:'planned'};
model=saveSavingsEntry(model,input,stamp);
model=saveSavingsEntry(model,{...input,id:'extra',amountMinor:3000,source:'extra'},stamp);
assert.equal(model.savings.buckets[0].balanceMinor,18000);
assert.deepEqual(model.budget,before.budget,'Actual deposits never change the plan');
assert.deepEqual(model.period,before.period);
assert.equal(model.savings.entries.length,2);
assert.equal(model.savings.entries[0].revision,0);
assert.throws(()=>saveSavingsEntry(model,input,stamp),/CONFLICT/,'A double submission must not add money twice');
assert.throws(()=>saveSavingsEntry(model,{...input,id:'bad',date:'2026-02-30'},stamp),/DATE/);
assert.throws(()=>saveSavingsEntry(model,{...input,id:'bad',amountMinor:1.1},stamp),/AMOUNT/);
assert.throws(()=>saveSavingsEntry(model,{...input,id:'bad',currency:'USD'},stamp),/CURRENCY/);
assert.throws(()=>saveSavingsEntry(model,{...input,id:'bad',source:'other'},stamp),/SOURCE/);
const changed=saveSavingsEntry(model,{...input,amountMinor:14000,source:'extra',expectedRevision:0},stamp);
assert.equal(changed.savings.buckets[0].balanceMinor,17000);
assert.equal(model.savings.buckets[0].balanceMinor,18000,'Functional updates never mutate the previous document');
assert.deepEqual(changed.savings.entries[0].history[0],{date:input.date,amountMinor:15000,source:'planned',status:'active',revision:0});
assert.equal(saveSavingsEntry(changed,{...input,amountMinor:14000,source:'extra',expectedRevision:1},stamp),changed,'No-op does not create a history revision or cloud write');
assert.throws(()=>saveSavingsEntry(changed,{...input,expectedRevision:0},stamp),/CONFLICT/);
assert.throws(()=>cancelSavingsEntry(changed,'first',0,stamp),/CONFLICT/);
const cancelled=cancelSavingsEntry(changed,'extra',0,stamp);
assert.equal(cancelled.savings.buckets[0].balanceMinor,14000);
assert.equal(cancelled.savings.entries.length,2,'Cancellation preserves the historical record');
assert.equal(cancelSavingsEntry(cancelled,'extra',0,stamp),cancelled,'Repeated cancellation never subtracts twice');
assert.throws(()=>saveSavingsEntry(cancelled,{...input,id:'extra',expectedRevision:1},stamp),/UNAVAILABLE/);
const disabled=updateSavingsBucket(cancelled,'travel',{active:false});
assert.throws(()=>saveSavingsEntry(disabled,{...input,id:'new'},stamp),/INACTIVE/);
assert.equal(cancelSavingsEntry(disabled,'first',1,stamp).savings.buckets[0].balanceMinor,0,'Old records can be annulled even if their category is inactive');
assert.deepEqual(migrateFinanceEvolution(JSON.parse(JSON.stringify(cancelled))),cancelled);
assert.deepEqual(mergeFinanceEvolution(cancelled,cancelled),cancelled);
assert.throws(()=>mergeFinanceEvolution(model,cancelled),/CONFLICT/);
const corrupt=structuredClone(cancelled);corrupt.savings.buckets[0].balanceMinor++;
assert.throws(()=>migrateFinanceEvolution(corrupt),/LEDGER_BALANCE/);
const corruptHistory=structuredClone(cancelled);corruptHistory.savings.entries[1].history=[];
assert.throws(()=>migrateFinanceEvolution(corruptHistory),/HISTORY/);
let old=createSavingsBucket(createFinanceEvolution(),{id:'travel',name:'Legacy',currency:'EUR'});
old.savings.buckets[0].balanceMinor=4567;old.savings.buckets[0].goalId='goal';old.savings.entries=[{id:'legacy',bucketId:'travel',amountMinor:4567,source:'residual'}];
old=saveSavingsEntry(old,input,stamp);
assert.equal(old.savings.buckets[0].openingBalanceMinor,4567);
assert.equal(old.savings.buckets[0].balanceMinor,19567);
assert.equal(cancelSavingsEntry(old,'first',0,stamp).savings.buckets[0].balanceMinor,4567);
assert.equal(old.savings.buckets[0].goalId,'goal');
for(const [text,minor] of [['150',15000],['30,25',3025],['0.01',1],[' 12.30 ',1230]])assert.equal(savingsAmountMinor(text),minor);
for(const text of ['','-1','0','1.001','1,000.00','1e3','NaN','9007199254740991'])assert.throws(()=>savingsAmountMinor(text),/AMOUNT/);
const {ledgerTranslationRows}=loadTypeScript('src/i18n/savingsLedgerTranslations.ts');
assert.equal(Object.keys(ledgerTranslationRows).length,10);
for(const [lang,row] of Object.entries(ledgerTranslationRows)){assert.equal(row.length,24,lang);assert(row.every(text=>typeof text==='string'&&text.trim()),lang);}
console.log('Savings ledger: 150+30=180, revision deltas, cancellation, stale writes, no duplicates, legacy opening funds, backup consistency and 10 languages passed');
