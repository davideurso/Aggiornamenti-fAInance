import assert from 'node:assert/strict';
import {createFinanceEvolution,migrateFinanceEvolution,mergeFinanceEvolution} from '../src/data/financeEvolution.js';
import {createSavingsBucket} from '../src/finance/savingsBuckets.js';
import {saveSavingsEntry,cancelSavingsEntry} from '../src/finance/savingsLedger.js';
import {linkSavingsGoal,goalSavedAmount,goalSavingsMinor} from '../src/finance/savingsGoals.js';

const goals=[{id:1,name:'Viaggio',target:1000,saved:40},{id:'next',name:'Casa',target:3000,saved:10}];
let data=createSavingsBucket(createFinanceEvolution(),{id:'travel',name:'Viaggio',currency:'EUR'});
const entry={id:'old',bucketId:'travel',currency:'EUR',date:'2026-09-14',amountMinor:5000,source:'planned'};
data=saveSavingsEntry(data,entry);
data=linkSavingsGoal(data,'travel','1',goals,'EUR',null);
assert.equal(goalSavedAmount(data,goals[0],'EUR'),40,'Existing bucket balance is not retroactively added');
data=saveSavingsEntry(data,{...entry,id:'first',amountMinor:15000,expectedGoalId:'1'});
assert.equal(goalSavedAmount(data,goals[0],'EUR'),190);
data=saveSavingsEntry(data,{...entry,id:'extra',source:'extra',amountMinor:3000,includeGoal:false});
assert.equal(goalSavedAmount(data,goals[0],'EUR'),190,'Extra can belong only to the bucket');
data=linkSavingsGoal(data,'travel','next',goals,'EUR','1');
assert.equal(goalSavedAmount(data,goals[0],'EUR'),190,'Relinking leaves accrued progress on the previous goal');
data=saveSavingsEntry(data,{...entry,id:'second',amountMinor:8000,source:'extra'});
assert.equal(goalSavedAmount(data,goals[1],'EUR'),90);
data=saveSavingsEntry(data,{...entry,id:'first',amountMinor:14000,expectedRevision:0});
assert.equal(goalSavedAmount(data,goals[0],'EUR'),180,'Correction adjusts the original goal');
assert.equal(goalSavedAmount(data,goals[1],'EUR'),90);
assert.throws(()=>saveSavingsEntry(data,{...entry,id:'stale',expectedGoalId:'1'}),/CONFLICT/);
assert.throws(()=>linkSavingsGoal(data,'travel','1',goals,'EUR','1'),/CONFLICT/);
data=cancelSavingsEntry(data,'first',1);
assert.equal(goalSavedAmount(data,goals[0],'EUR'),40);
assert.equal(goalSavedAmount(data,goals[1],'EUR'),90);
assert.deepEqual(goals,[{id:1,name:'Viaggio',target:1000,saved:40},{id:'next',name:'Casa',target:3000,saved:10}],'No second write to goals or manual savings');
data=linkSavingsGoal(data,'travel',null,goals,'EUR','next');
assert.equal(goalSavedAmount(data,goals[1],'EUR'),90,'Unlink preserves progress');
assert.equal(goalSavingsMinor(data,goals[1],'USD'),0,'Different currencies are never added');
assert.throws(()=>linkSavingsGoal(data,'travel','missing',goals,'EUR',null),/UNAVAILABLE/);
assert.throws(()=>linkSavingsGoal(data,'travel','next',goals,'USD',null),/CURRENCY/);
assert.throws(()=>linkSavingsGoal(data,'travel','done',[{id:'done',target:10,saved:10}],'EUR',null),/COMPLETE/);
const restored=migrateFinanceEvolution(JSON.parse(JSON.stringify(data)));
assert.equal(goalSavedAmount(restored,goals[1],'EUR'),90);
assert.deepEqual(mergeFinanceEvolution(data,restored),data,'Repeated restore does not duplicate progress');
const broken=structuredClone(data);broken.savings.entries[0].goalId=17;
assert.throws(()=>migrateFinanceEvolution(broken),/GOAL/);
console.log('Goal linking: no retroactive allocation, extra opt-out, relink preservation, corrections, cancellation, stale updates, currency isolation and backup passed');
