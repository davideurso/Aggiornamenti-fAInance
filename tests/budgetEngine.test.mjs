import assert from 'node:assert/strict';
import { createFinanceEvolution } from '../src/data/financeEvolution.js';
import { budgetForPeriod, saveBudgetForPeriod, resetBudgetForPeriod, budgetSourceForPeriod, budgetReferenceIncome, budgetPeriodSummary, averageBudgetForPeriods } from '../src/finance/budgetEngine.js';
import { budgetEditorItems, updateBudgetItem, repriceBudgetItems, preserveHiddenBudgetItems } from '../src/finance/budgetEditor.js';
import { migrateFinanceEvolution, mergeFinanceEvolution } from '../src/data/financeEvolution.js';
const legacy = { income: 3000, manualIncome: 3000, items: [{ catId: 'restaurants', amount: 200 }] };
const august = { ...legacy, items: [{ catId: 'restaurants', amount: 350 }] };
const finance = saveBudgetForPeriod(createFinanceEvolution(),legacy,'2026-08',august,'month');
assert.equal(budgetForPeriod(finance,legacy,'2026-08').items[0].amount,350);
assert.equal(budgetForPeriod(finance,legacy,'2026-09').items[0].amount,200);
assert.equal(budgetForPeriod(finance,legacy,'2025-01').items[0].amount,200);
const recurring=saveBudgetForPeriod(finance,legacy,'2026-09',august,'future');
assert.equal(budgetForPeriod(recurring,legacy,'2026-10').items[0].amount,350);
assert.equal(budgetForPeriod(recurring,legacy,'2026-07').items[0].amount,200);
assert.equal(legacy.items[0].amount,200);
assert.equal(averageBudgetForPeriods(key=>budgetForPeriod(finance,legacy,key),['2026-08','2026-09']).items[0].amount,275);
assert.equal(averageBudgetForPeriods(key=>budgetForPeriod(recurring,legacy,key),['2026-08','2026-09']).items[0].amount,350);
const financial={mode:'financial',startDay:27};
const plan={income:3000,items:[{catId:'all',amount:2700}]};
const summary=budgetPeriodSummary([{date:'2026-06-26',amount:2800}],[{date:'2026-05-27',amount:3000}],plan,'2026-06',financial);
assert.equal(summary.realSaving,200);
assert.equal(summary.plannedSaving,300);
assert.equal(summary.planAchievement,2/3);
assert.equal(summary.actualSavingsRate,1/15);
assert.equal(summary.difference,200);
const deficit=budgetPeriodSummary([{date:'2026-06-26',amount:120}],[],{income:0,items:[]},'2026-06',financial);
assert.equal(deficit.realSaving,-120);
assert.equal(deficit.actualSavingsRate,null);
assert.equal(deficit.planAchievement,null);
assert.throws(()=>saveBudgetForPeriod(finance,legacy,'2026-08',{income:0,items:[{catId:'a',amount:-5}]},'month'));
assert.deepEqual(JSON.parse(JSON.stringify(recurring)),recurring);
const reset=resetBudgetForPeriod(finance,'2026-08');
assert.equal(budgetForPeriod(reset,legacy,'2026-08').items[0].amount,200);
assert.equal(budgetSourceForPeriod(finance,'2026-08').kind,'month');
assert.equal(budgetSourceForPeriod(reset,'2026-08').kind,'standard');
assert.equal(finance.budget.overrides['2026-08'].items[0].amount,350,'Reset must not mutate its source');
let scheduled=saveBudgetForPeriod(recurring,legacy,'2026-12',{...legacy,income:5000},'future');
scheduled=saveBudgetForPeriod(scheduled,legacy,'2026-11',{...legacy,income:1500},'month');
scheduled=saveBudgetForPeriod(scheduled,legacy,'2026-10',{...legacy,income:4200},'future');
assert.equal(budgetForPeriod(scheduled,legacy,'2027-01').income,4200,'From this month onward replaces later standards');
assert.equal(budgetForPeriod(scheduled,legacy,'2026-11').income,1500,'Explicit exceptions in other months survive');
assert.equal(budgetForPeriod(scheduled,legacy,'2026-09').items[0].amount,350,'Past standards survive');
assert.deepEqual(migrateFinanceEvolution(JSON.parse(JSON.stringify(scheduled))),scheduled);
assert.deepEqual(mergeFinanceEvolution(scheduled,scheduled),scheduled,'Identical backup merge is idempotent');
assert.equal(budgetReferenceIncome({income:3000,manualIncome:0}),0,'Explicit zero must not fall back to average income');
const categories=[{id:'restaurants'}];
let draft=budgetEditorItems({income:3000,items:[{catId:'restaurants',amount:350,pct:12}]},categories);
assert.equal(repriceBudgetItems(draft,3000)[0].amount,350,'Rounded 12% must not change saved 350 into 360');
draft=updateBudgetItem(draft,'restaurants',350,'amount',3000);
assert.equal(repriceBudgetItems(draft,5000)[0].amount,350,'A fixed amount stays fixed after income changes');
draft=updateBudgetItem(draft,'restaurants',12,'percent',3000);
assert.equal(draft[0].amount,360);
assert.equal(repriceBudgetItems(draft,5000)[0].amount,600);
assert.equal(repriceBudgetItems(draft,0)[0].amount,0);
const hidden={catId:'archived-category',amount:60.25,pct:2.01,customField:'preserved'};
assert.deepEqual(preserveHiddenBudgetItems({items:[hidden]},draft)[1],hidden,'Editing visible categories must preserve archived allocations');
const modePlan={income:3000,items:draft};
assert.deepEqual(budgetForPeriod(migrateFinanceEvolution(JSON.parse(JSON.stringify(saveBudgetForPeriod(reset,legacy,'2026-08',modePlan,'month')))),legacy,'2026-08'),modePlan);
for(const comparison of ['previous','previousYear','average6','average12']){
  const result=budgetPeriodSummary([{date:'2026-06-26',amount:2800}],[{date:'2026-05-27',amount:3000}],plan,'2026-06',financial,comparison);
  assert.equal(result.realSaving,200);
  assert.equal(result.comparisonKeys.length,comparison==='average6'?6:comparison==='average12'?12:1);
}
console.log('Budget: monthly overrides, recurring versions, preserved history, KPI formulas and zero denominators passed');
