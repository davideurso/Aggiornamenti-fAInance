import assert from 'node:assert/strict';
import { createFinanceEvolution, migrateFinanceEvolution, mergeFinanceEvolution, selectFinanceEvolution } from '../src/data/financeEvolution.js';
const old = { budgetPlan: { income: 1234, items: [{ catId: 'food', amount: 100 }] }, expenses: [{ amount: 123, date: '2025-02-01' }] };
const original = JSON.stringify(old);
const migrated = { ...old, financeEvolution: migrateFinanceEvolution(old.financeEvolution) };
assert.equal(JSON.stringify(old), original);
assert.deepEqual(migrated.budgetPlan, old.budgetPlan);
assert.equal(migrated.financeEvolution.period.mode, 'calendar');
assert.deepEqual(migrated.financeEvolution.savings.entries, []);
assert.deepEqual(migrateFinanceEvolution(migrated.financeEvolution), migrated.financeEvolution);
const populated = createFinanceEvolution();
populated.period = { mode: 'financial', startDay: 31 };
populated.savings.buckets = [{ id: 'trip', name: 'Trip', active: true, plannedMinor: 10000, balanceMinor: 15000, currency: 'EUR', goalId: 'goal1' }];
populated.savings.entries = [{ id: 'e1', bucketId: 'trip', amountMinor: 15000, currency: 'EUR', source: 'extra', goalId: 'goal1', goalAmountMinor: 15000, date: '2026-08-30', periodKey: '2026-08' }];
populated.savings.deficits = [{ id: 'd1', periodKey: '2026-07', originalMinor: 12000, currency: 'EUR', status: 'uncovered' }];
populated.rules = [{ id: 'r1', name: 'Biliardo', enabled: true, priority: 1, trigger: 'expense', match: 'all', conditions: [], actions: [], alert: null }];
populated.tools.calculator = [{ id: 'c1', result: 42, createdAt: '2026-09-10T10:00:00Z' }];
populated.extraFutureField = { preserve: true };
const roundtrip = migrateFinanceEvolution(JSON.parse(JSON.stringify(populated)));
assert.deepEqual(roundtrip, populated);
assert.deepEqual(mergeFinanceEvolution(populated, roundtrip), populated);
assert.deepEqual(selectFinanceEvolution(populated, undefined, 1, 999), populated);
assert.deepEqual(selectFinanceEvolution(undefined, populated, 0, 1), populated);
assert.deepEqual(selectFinanceEvolution(populated, createFinanceEvolution(), 20, 10), populated);
assert.throws(() => migrateFinanceEvolution({ schemaVersion: 999 }), /UNSUPPORTED/);
assert.throws(() => migrateFinanceEvolution({ rules: 'invalid' }), /INVALID/);
assert.throws(() => migrateFinanceEvolution({ savings: { buckets: [{ id: 'bad', balanceMinor: -1 }] } }), /BALANCE/);
assert.throws(() => mergeFinanceEvolution(populated, createFinanceEvolution()), /PERIOD_CONFLICT/);
const conflict = structuredClone(populated);
conflict.savings.entries[0].amountMinor = 90000;
assert.throws(() => mergeFinanceEvolution(populated, conflict), /CONFLICT/);
assert.equal(populated.savings.entries[0].amountMinor, 15000);
console.log('Finance model: migration, roundtrip, merge conflicts and sync selection passed');
